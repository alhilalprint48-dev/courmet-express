import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {requireSafePassword,PasswordSafetyError} from '../src/lib/password-safety.mjs';
const sample='Example password for fixtures only!';
const hash=createHash('sha1').update(sample).digest('hex').toUpperCase();
let checks=0;
const check=(name,actual,expected)=>{assert.deepEqual(actual,expected);checks++;console.log('PASS',name);};
const fail=async(name,work,code)=>{await assert.rejects(work,e=>e instanceof PasswordSafetyError&&e.code===code);checks++;console.log('PASS',name);};
let sent;
await requireSafePassword(sample,{request:async(url,options)=>{sent={url,options};return new Response(`${'A'.repeat(35)}:1\r\n${hash.slice(5)}:0`);}});
check('only five hash characters leave the client',sent.url,`https://api.pwnedpasswords.com/range/${hash.slice(0,5)}`);
check('credentials are omitted',sent.options.credentials,'omit');
check('referrer is omitted',sent.options.referrerPolicy,'no-referrer');
check('padding requested',sent.options.headers,{'Add-Padding':'true'});
check('no request body',sent.options.body,undefined);
await fail('compromised password refused',()=>requireSafePassword(sample,{request:async()=>new Response(`${hash.slice(5)}:92`)}),'compromised');
await fail('lowercase suffix matches',()=>requireSafePassword(sample,{request:async()=>new Response(`${hash.slice(5).toLowerCase()}:1`)}),'compromised');
await fail('provider outage blocks validation',()=>requireSafePassword(sample,{request:async()=>new Response('error',{status:503})}),'unavailable');
await fail('network timeout blocks validation',()=>requireSafePassword(sample,{request:async()=>{throw new DOMException('Timed out','TimeoutError');}}),'unavailable');
for(const body of ['', '<html>Error</html>', `${'B'.repeat(35)}:1\ninvalid`]) await fail('malformed response refused',()=>requireSafePassword(sample,{request:async()=>new Response(body)}),'unavailable');
let called=false;
await fail('short password refused without network call',()=>requireSafePassword('short',{request:async()=>{called=true;return new Response('');}}),'too_short');
check('short password never sent',called,false);
await fail('excessive length refused',()=>requireSafePassword('x'.repeat(1025)),'too_long');
await fail('missing crypto blocks validation',()=>requireSafePassword(sample,{cryptography:{},request:async()=>new Response('')}),'unavailable');
console.log(`${checks} password screening checks passed; no real passwords, accounts or messages.`);
